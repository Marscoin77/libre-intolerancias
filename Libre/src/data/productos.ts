  calidad: 1 | 2 | 3 | 4 | 5;
  supermercados: string[];
  dietas?: DietaId[];
  /** URL de foto real (Open Food Facts); si falta se muestra una ilustración */
  imagen?: string;
  /** 'real' viene de Open Prices; 'estimado' es una mediana por categoría */
